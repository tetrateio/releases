// Command formula writes the Homebrew formula of a promoted release into a
// checkout of the tap, from the release's manifest in this repository:
//
//	go run ./tools/formula -product tetrate -tap ../homebrew-tap
//
// Without -version it uses the newest release that the index names: the
// newest stable release, or the newest prerelease while no stable release
// exists. It writes Formula/<product>.rb and changes nothing else. Commit
// and push the tap yourself, or pass -commit to commit and push it with a
// signed commit.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"text/template"
)

func main() {
	product := flag.String("product", "", "the product, a directory of this repository")
	version := flag.String("version", "", "the version; the newest in the index when empty")
	dir := flag.String("dir", ".", "the checkout of this repository")
	tap := flag.String("tap", "", "the checkout of the Homebrew tap")
	commit := flag.Bool("commit", false, "commit the formula with a signed commit and push the tap")
	flag.Parse()
	if *product == "" || *tap == "" || flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "usage: formula -product <name> -tap <dir> [-version vX] [-commit]")
		os.Exit(2)
	}
	if err := run(*dir, *tap, *product, *version, *commit); err != nil {
		fmt.Fprintln(os.Stderr, "formula:", err)
		os.Exit(1)
	}
}

func run(dir, tap, product, version string, commit bool) error {
	if version == "" {
		v, err := newest(filepath.Join(dir, product, "index.json"))
		if err != nil {
			return err
		}
		version = v
	}
	b, err := os.ReadFile(filepath.Join(dir, product, version+".json"))
	if err != nil {
		return fmt.Errorf("%s %s is not promoted: %w", product, version, err)
	}
	var m manifest
	if err := json.Unmarshal(b, &m); err != nil {
		return err
	}
	rb, err := render(m)
	if err != nil {
		return err
	}
	path := filepath.Join(tap, "Formula", product+".rb")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, rb, 0o644); err != nil {
		return err
	}
	fmt.Printf("Wrote %s for %s %s\n", path, product, version)
	if !commit {
		return nil
	}
	rel := filepath.Join("Formula", product+".rb")
	if out, err := git(tap, "status", "--porcelain", "--", rel); err != nil {
		return err
	} else if out == "" {
		fmt.Println("The formula is unchanged")
		return nil
	}
	for _, args := range [][]string{
		{"add", "--", rel},
		{"commit", "-S", "-m", fmt.Sprintf("Update %s to %s", product, version)},
		{"push", "origin", "HEAD:main"},
	} {
		if _, err := git(tap, args...); err != nil {
			return err
		}
	}
	fmt.Printf("Pushed the %s formula for %s\n", product, version)
	return nil
}

// newest reads the index and returns the version the installer would pick.
func newest(path string) (string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	var idx struct {
		Latest struct {
			Stable     *string `json:"stable"`
			Prerelease *string `json:"prerelease"`
		} `json:"latest"`
	}
	if err := json.Unmarshal(b, &idx); err != nil {
		return "", err
	}
	switch {
	case idx.Latest.Stable != nil:
		return *idx.Latest.Stable, nil
	case idx.Latest.Prerelease != nil:
		return *idx.Latest.Prerelease, nil
	}
	return "", errors.New("the index names no release")
}

type manifest struct {
	Product string `json:"product"`
	Version string `json:"version"`
	Release string `json:"release"`
	Source  struct {
		Repo string `json:"repo"`
	} `json:"source"`
	Assets []struct {
		Platform string `json:"platform"`
		SHA256   string `json:"sha256"`
		URL      string `json:"url"`
	} `json:"assets"`
}

// platforms maps a manifest platform to the Homebrew blocks that select it.
var platforms = map[string][2]string{
	"darwin-arm64": {"on_macos", "on_arm"},
	"linux-amd64":  {"on_linux", "on_intel"},
	"linux-arm64":  {"on_linux", "on_arm"},
}

type download struct{ URL, SHA256 string }

type formulaData struct {
	Class, Desc, Homepage, Version, Product string
	MacArm, LinuxIntel, LinuxArm            *download
}

const formulaTmpl = `# Generated by tools/formula in tetrateio/releases from {{.Product}}/v{{.Version}}.json. Do not edit.
class {{.Class}} < Formula
  desc "{{.Desc}}"
  homepage "{{.Homepage}}"
  version "{{.Version}}"
  license :cannot_represent

  on_macos do
    depends_on arch: :arm64
{{- with .MacArm}}
    url "{{.URL}}"
    sha256 "{{.SHA256}}"
{{- end}}
  end

  on_linux do
{{- with .LinuxIntel}}
    on_intel do
      url "{{.URL}}"
      sha256 "{{.SHA256}}"
    end
{{- end}}
{{- with .LinuxArm}}
    on_arm do
      url "{{.URL}}"
      sha256 "{{.SHA256}}"
    end
{{- end}}
  end

  def install
    bin.install Dir["{{.Product}}-*"].first => "{{.Product}}"
    generate_completions_from_executable(bin/"{{.Product}}", "completion")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/{{.Product}} version")
  end
end
`

func render(m manifest) ([]byte, error) {
	if m.Product == "" || !strings.HasPrefix(m.Version, "v") {
		return nil, fmt.Errorf("the manifest has no product or version")
	}
	d := formulaData{
		Class:    strings.ToUpper(m.Product[:1]) + m.Product[1:],
		Desc:     "Install, verify and run Tetrate products",
		Homepage: "https://github.com/tetrateio/releases",
		Version:  strings.TrimPrefix(m.Version, "v"),
		Product:  m.Product,
	}
	for _, a := range m.Assets {
		if len(a.SHA256) != 64 || !strings.HasPrefix(a.URL, "https://github.com/tetrateio/releases/releases/download/") {
			return nil, fmt.Errorf("asset %s has an unexpected sha256 or URL", a.Platform)
		}
		dl := &download{URL: a.URL, SHA256: a.SHA256}
		switch a.Platform {
		case "darwin-arm64":
			d.MacArm = dl
		case "linux-amd64":
			d.LinuxIntel = dl
		case "linux-arm64":
			d.LinuxArm = dl
		default:
			return nil, fmt.Errorf("platform %s has no Homebrew block", a.Platform)
		}
	}
	if d.MacArm == nil || d.LinuxIntel == nil || d.LinuxArm == nil {
		return nil, fmt.Errorf("%s %s lacks a platform; the formula needs %d", m.Product, m.Version, len(platforms))
	}
	var b bytes.Buffer
	if err := template.Must(template.New("formula").Parse(formulaTmpl)).Execute(&b, d); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

func git(dir string, args ...string) (string, error) {
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	var out, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &stderr
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("git %s: %s", strings.Join(args, " "), strings.TrimSpace(stderr.String()))
	}
	return strings.TrimSpace(out.String()), nil
}
